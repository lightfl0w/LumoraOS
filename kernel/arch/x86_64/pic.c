#include "pic.h"

#include "io.h"

void pic_setup(void) {
    out8(0x20, 0x11); /* ICW1 */
    out8(0xa0, 0x11);
    out8(0x21, 0x20); /* ICW2 */
    out8(0xa1, 0x28);
    out8(0x21, 0x04); /* ICW3 */
    out8(0xa1, 0x02);
    out8(0x21, 0x01); /* ICW4 */
    out8(0xa1, 0x01);
    out8(0x21, 0xff); /* 全屏蔽 */
    out8(0xa1, 0xff);
}
